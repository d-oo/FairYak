CREATE OR REPLACE FUNCTION "public"."clear_recommended_locations_for_meeting"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  DELETE FROM recommended_locations
  WHERE meeting_id = COALESCE(NEW.meeting_id, OLD.meeting_id);
  RETURN NULL;
END;
$$;


ALTER FUNCTION "public"."clear_recommended_locations_for_meeting"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."copy_location_to_member"("p_user_id" "uuid", "p_meeting_id" bigint, "p_location_name" "text") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  UPDATE members
  SET
    departure_location = (
      SELECT location::geography
      FROM user_locations
      WHERE user_id = p_user_id AND name = p_location_name
    ),
    departure_address = (
      SELECT address
      FROM user_locations
      WHERE user_id = p_user_id AND name = p_location_name
    )
  WHERE user_id = p_user_id AND meeting_id = p_meeting_id;
END;
$$;


ALTER FUNCTION "public"."copy_location_to_member"("p_user_id" "uuid", "p_meeting_id" bigint, "p_location_name" "text") OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."handle_new_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  INSERT INTO public.profiles (id, name, email)
  VALUES (
    NEW.id,
    NEW.raw_user_meta_data ->> 'name',
    NEW.email
  );
  RETURN NEW;
END;
$$;


ALTER FUNCTION "public"."handle_new_user"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."log_member_joined"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  INSERT INTO meeting_logs (meeting_id, user_name, type)
  VALUES (
    NEW.meeting_id,
    (SELECT name FROM profiles WHERE id = NEW.user_id),
    'member_joined'
  );
  RETURN NULL;
END;
$$;


ALTER FUNCTION "public"."log_member_joined"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."log_member_left"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  INSERT INTO meeting_logs (meeting_id, user_name, type)
  VALUES (
    OLD.meeting_id,
    (SELECT name FROM profiles WHERE id = OLD.user_id),
    'member_left'
  );
  RETURN NULL;
END;
$$;


